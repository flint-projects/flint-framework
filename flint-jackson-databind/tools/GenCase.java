// Writes framework/jackson-databind/source/flint/jackson/databind/casing.d: JDK 21's Character.toLowerCase,
// Character.toUpperCase and Character.isUpperCase as range tables, so the naming strategies and
// WRITE_ENUMS_TO_LOWERCASE need no std.uni.
//   javac GenCase.java && java GenCase ../source/flint/jackson/databind/casing.d, then format it with dfmt
//   (--config at the repository root) and keep its hand-written unit test at the end.
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.function.IntUnaryOperator;

public class GenCase {
    // Runs of code points start..end (every `step`-th one) that map to themselves plus `delta`.
    static List<int[]> runs(IntUnaryOperator map) {
        List<int[]> out = new ArrayList<>();
        int cp = 0;
        while (cp <= Character.MAX_CODE_POINT) {
            int delta = map.applyAsInt(cp) - cp;
            if (delta == 0) { cp++; continue; }
            // Try a contiguous run, then an alternating one (Latin Extended pairs), keep the longer.
            int end1 = cp;
            while (end1 + 1 <= Character.MAX_CODE_POINT && map.applyAsInt(end1 + 1) - (end1 + 1) == delta) end1++;
            int end2 = cp;
            while (end2 + 2 <= Character.MAX_CODE_POINT && map.applyAsInt(end2 + 2) - (end2 + 2) == delta
                    && map.applyAsInt(end2 + 1) == end2 + 1 + (delta == 1 || delta == -1 ? -delta : 0)) end2 += 2;
            if (end2 > end1) { out.add(new int[] {cp, end2, delta, 2}); cp = end2 + 1; }
            else { out.add(new int[] {cp, end1, delta, 1}); cp = end1 + 1; }
        }
        return out;
    }

    static List<int[]> upperRanges() {
        List<int[]> out = new ArrayList<>();
        int cp = 0;
        while (cp <= Character.MAX_CODE_POINT) {
            if (!Character.isUpperCase(cp)) { cp++; continue; }
            int end = cp;
            while (end + 1 <= Character.MAX_CODE_POINT && Character.isUpperCase(end + 1)) end++;
            out.add(new int[] {cp, end});
            cp = end + 1;
        }
        return out;
    }

    static void table(StringBuilder b, String name, List<int[]> runs) {
        b.append("private static immutable CaseRun[").append(runs.size()).append("] ").append(name).append(" = [\n");
        for (int[] r : runs)
            b.append(String.format("    CaseRun(0x%X, 0x%X, %d, %d),%n", r[0], r[1], r[2], r[3]));
        b.append("];\n\n");
    }

    public static void main(String[] args) throws Exception {
        List<int[]> lower = runs(Character::toLowerCase), upper = runs(Character::toUpperCase);
        List<int[]> isUpper = upperRanges();
        // Self-check: the tables reproduce the JDK for every code point.
        for (int cp = 0; cp <= Character.MAX_CODE_POINT; cp++) {
            if (apply(lower, cp) != Character.toLowerCase(cp)) throw new AssertionError("lower " + cp);
            if (apply(upper, cp) != Character.toUpperCase(cp)) throw new AssertionError("upper " + cp);
        }
        StringBuilder b = new StringBuilder();
        b.append("// Generated by framework/jackson-databind/tools/GenCase.java from JDK ")
            .append(System.getProperty("java.version")).append(". Do not edit.\n");
        b.append("/// Java's `Character.toLowerCase`, `toUpperCase` and `isUpperCase` (simple, per code point).\n");
        b.append("module flint.jackson.databind.casing;\n\n@safe:\n\n");
        b.append("""
            /// `Character.toLowerCase(c)`.
            dchar toLowerCase(dchar c) pure nothrow @nogc
            {
                if (c < 0x80)
                    return c >= 'A' && c <= 'Z' ? cast(dchar)(c + 32) : c;
                return mapped(lowerRuns, c);
            }

            /// `Character.toUpperCase(c)`.
            dchar toUpperCase(dchar c) pure nothrow @nogc
            {
                if (c < 0x80)
                    return c >= 'a' && c <= 'z' ? cast(dchar)(c - 32) : c;
                return mapped(upperRuns, c);
            }

            /// `Character.isUpperCase(c)`.
            bool isUpperCase(dchar c) pure nothrow @nogc
            {
                if (c < 0x80)
                    return c >= 'A' && c <= 'Z';
                size_t low, high = upperCaseRanges.length;
                while (low < high)
                {
                    const middle = (low + high) / 2;
                    if (c < upperCaseRanges[middle][0])
                        high = middle;
                    else if (c > upperCaseRanges[middle][1])
                        low = middle + 1;
                    else
                        return true;
                }
                return false;
            }

            private struct CaseRun
            {
                uint start, end;
                int delta;
                uint step;
            }

            private dchar mapped(scope const(CaseRun)[] runs, dchar c) pure nothrow @nogc
            {
                size_t low, high = runs.length;
                while (low < high)
                {
                    const middle = (low + high) / 2;
                    const run = runs[middle];
                    if (c < run.start)
                        high = middle;
                    else if (c > run.end)
                        low = middle + 1;
                    else
                        return (c - run.start) % run.step == 0 ? cast(dchar)(c + run.delta) : c;
                }
                return c;
            }

            """);
        table(b, "lowerRuns", lower);
        table(b, "upperRuns", upper);
        b.append("private static immutable uint[2][").append(isUpper.size()).append("] upperCaseRanges = [\n");
        for (int[] r : isUpper) b.append(String.format("    [0x%X, 0x%X],%n", r[0], r[1]));
        b.append("];\n");
        Files.writeString(Path.of(args[0]), b.toString(), StandardCharsets.UTF_8);
        System.out.println(lower.size() + " lower runs, " + upper.size() + " upper runs, " + isUpper.size() + " upper ranges");
    }

    static int apply(List<int[]> runs, int cp) {
        for (int[] r : runs)
            if (cp >= r[0] && cp <= r[1] && (cp - r[0]) % r[3] == 0) return cp + r[2];
        return cp;
    }
}
